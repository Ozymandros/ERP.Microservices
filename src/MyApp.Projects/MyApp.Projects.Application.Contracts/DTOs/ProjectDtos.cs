using System.ComponentModel.DataAnnotations;
using MyApp.Projects.Domain.Entities;
using MyApp.Shared.Domain.DTOs;

namespace MyApp.Projects.Application.Contracts.DTOs;

/// <summary>Project read model.</summary>
public record ProjectDto(Guid Id) : AuditableGuidDto(Id)
{
    /// <summary>Gets the project number.</summary>
    public string ProjectNumber { get; init; } = string.Empty;
    /// <summary>Gets the description.</summary>
    public string Description { get; init; } = string.Empty;
    /// <summary>Gets the bill-to customer id (Sales).</summary>
    public Guid CustomerId { get; init; }
    /// <summary>Gets the project manager user id (Auth).</summary>
    public Guid? ProjectManagerUserId { get; init; }
    /// <summary>Gets the status.</summary>
    public string Status { get; init; } = string.Empty;
    /// <summary>Gets the blocking level.</summary>
    public string Blocked { get; init; } = string.Empty;
    /// <summary>Gets the starting date.</summary>
    public DateTime? StartingDate { get; init; }
    /// <summary>Gets the ending date.</summary>
    public DateTime? EndingDate { get; init; }
    /// <summary>Gets the project currency.</summary>
    public string CurrencyCode { get; init; } = string.Empty;
    /// <summary>Gets the external reference.</summary>
    public string? ExternalReference { get; init; }
}

/// <summary>Payload to create a project. The number is generated by the backend.</summary>
public record CreateProjectDto
{
    /// <summary>Gets the description.</summary>
    [Required, StringLength(250, MinimumLength = 1)]
    public string Description { get; init; } = string.Empty;
    /// <summary>Gets the bill-to customer id (must exist in Sales).</summary>
    [Required]
    public Guid CustomerId { get; init; }
    /// <summary>Gets the project manager user id.</summary>
    public Guid? ProjectManagerUserId { get; init; }
    /// <summary>Gets the starting date.</summary>
    public DateTime? StartingDate { get; init; }
    /// <summary>Gets the ending date.</summary>
    public DateTime? EndingDate { get; init; }
    /// <summary>Gets the project currency (defaults to the local currency).</summary>
    [StringLength(3, MinimumLength = 3)]
    public string? CurrencyCode { get; init; }
    /// <summary>Gets the external reference.</summary>
    [StringLength(100)]
    public string? ExternalReference { get; init; }
}

/// <summary>Payload to update a project header.</summary>
public record UpdateProjectDto
{
    /// <summary>Gets the description.</summary>
    [Required, StringLength(250, MinimumLength = 1)]
    public string Description { get; init; } = string.Empty;
    /// <summary>Gets the bill-to customer id (must exist in Sales).</summary>
    [Required]
    public Guid CustomerId { get; init; }
    /// <summary>Gets the project manager user id.</summary>
    public Guid? ProjectManagerUserId { get; init; }
    /// <summary>Gets the starting date.</summary>
    public DateTime? StartingDate { get; init; }
    /// <summary>Gets the ending date.</summary>
    public DateTime? EndingDate { get; init; }
    /// <summary>Gets the project currency (only changeable while nothing has been posted or invoiced).</summary>
    [Required, StringLength(3, MinimumLength = 3)]
    public string CurrencyCode { get; init; } = string.Empty;
    /// <summary>Gets the blocking level.</summary>
    public ProjectBlocked Blocked { get; init; } = ProjectBlocked.None;
    /// <summary>Gets the external reference.</summary>
    [StringLength(100)]
    public string? ExternalReference { get; init; }
}

/// <summary>Payload to change the project status.</summary>
public record ChangeProjectStatusDto
{
    /// <summary>Gets the target status.</summary>
    [Required]
    public ProjectStatus Status { get; init; }
}

/// <summary>Payload to copy a project (tasks and, optionally, planning lines).</summary>
public record CopyProjectDto
{
    /// <summary>Gets the description of the new project (defaults to "Copy of ...").</summary>
    [StringLength(250)]
    public string? Description { get; init; }
    /// <summary>Gets the customer of the new project (defaults to the source customer).</summary>
    public Guid? CustomerId { get; init; }
    /// <summary>Gets whether planning lines are copied (quantities posted/invoiced are reset).</summary>
    public bool IncludePlanningLines { get; init; } = true;
}

/// <summary>Project task read model.</summary>
public record ProjectTaskDto(Guid Id) : AuditableGuidDto(Id)
{
    /// <summary>Gets the project id.</summary>
    public Guid ProjectId { get; init; }
    /// <summary>Gets the parent task id.</summary>
    public Guid? ParentTaskId { get; init; }
    /// <summary>Gets the task number.</summary>
    public string TaskNo { get; init; } = string.Empty;
    /// <summary>Gets the description.</summary>
    public string Description { get; init; } = string.Empty;
    /// <summary>Gets the task type.</summary>
    public string TaskType { get; init; } = string.Empty;
    /// <summary>Gets the sort order among siblings.</summary>
    public int SortOrder { get; init; }
    /// <summary>Gets the start date.</summary>
    public DateTime? StartDate { get; init; }
    /// <summary>Gets the end date.</summary>
    public DateTime? EndDate { get; init; }
}

/// <summary>Node of the project task tree.</summary>
public record ProjectTaskTreeNodeDto
{
    /// <summary>Gets the task.</summary>
    public ProjectTaskDto Task { get; init; } = new(Guid.Empty);
    /// <summary>Gets the depth (0 = root).</summary>
    public int Level { get; init; }
    /// <summary>Gets the children.</summary>
    public List<ProjectTaskTreeNodeDto> Children { get; init; } = new();
}

/// <summary>Payload to create a task.</summary>
public record CreateProjectTaskDto
{
    /// <summary>Gets the parent task id (null = root).</summary>
    public Guid? ParentTaskId { get; init; }
    /// <summary>Gets the task number (unique within the project).</summary>
    [Required, StringLength(20, MinimumLength = 1)]
    public string TaskNo { get; init; } = string.Empty;
    /// <summary>Gets the description.</summary>
    [Required, StringLength(250, MinimumLength = 1)]
    public string Description { get; init; } = string.Empty;
    /// <summary>Gets the task type.</summary>
    public ProjectTaskType TaskType { get; init; } = ProjectTaskType.Posting;
    /// <summary>Gets the sort order (defaults to last among siblings).</summary>
    public int? SortOrder { get; init; }
    /// <summary>Gets the start date.</summary>
    public DateTime? StartDate { get; init; }
    /// <summary>Gets the end date.</summary>
    public DateTime? EndDate { get; init; }
}

/// <summary>Payload to update a task (use the move endpoint to re-parent).</summary>
public record UpdateProjectTaskDto
{
    /// <summary>Gets the task number.</summary>
    [Required, StringLength(20, MinimumLength = 1)]
    public string TaskNo { get; init; } = string.Empty;
    /// <summary>Gets the description.</summary>
    [Required, StringLength(250, MinimumLength = 1)]
    public string Description { get; init; } = string.Empty;
    /// <summary>Gets the task type.</summary>
    public ProjectTaskType TaskType { get; init; } = ProjectTaskType.Posting;
    /// <summary>Gets the start date.</summary>
    public DateTime? StartDate { get; init; }
    /// <summary>Gets the end date.</summary>
    public DateTime? EndDate { get; init; }
}

/// <summary>Payload to move (re-parent / re-order) a task.</summary>
public record MoveProjectTaskDto
{
    /// <summary>Gets the new parent task id (null = root).</summary>
    public Guid? NewParentTaskId { get; init; }
    /// <summary>Gets the new sort order among siblings (defaults to last).</summary>
    public int? SortOrder { get; init; }
}
